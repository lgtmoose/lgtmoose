import type { FileDiff, Hunk } from "@lgtmoose/git";
import { describe, expect, it } from "vitest";
import { TEST_GLOBS, globMatcher, hasGeneratedMarker, skipClassifier } from "./classify.js";

function diff(path: string, overrides: Partial<FileDiff> = {}): FileDiff {
  return {
    path,
    status: "modified",
    oldBlob: "a".repeat(40),
    newBlob: "b".repeat(40),
    submodule: false,
    moved: false,
    mechanical: false,
    binary: false,
    hunks: [],
    ...overrides,
  };
}

function header(text: string, newLine = 1): Hunk {
  return {
    oldStart: 0,
    oldLines: 0,
    newStart: newLine,
    newLines: 1,
    section: "",
    lines: [{ kind: "add", newLine, text }],
  };
}

describe("skipClassifier", () => {
  const skip = skipClassifier([]);

  it.each([
    ["package-lock.json", "lockfile"],
    ["apps/web/pnpm-lock.yaml", "lockfile"],
    ["yarn.lock", "lockfile"],
    ["bun.lockb", "lockfile"],
    ["Cargo.lock", "lockfile"],
    ["go.sum", "lockfile"],
    ["poetry.lock", "lockfile"],
    ["composer.lock", "lockfile"],
    ["Gemfile.lock", "lockfile"],
    ["ios/Podfile.lock", "lockfile"],
    ["infra/.terraform.lock.hcl", "lockfile"],
    ["public/app.min.js", "minified"],
    ["styles/site.min.css", "minified"],
    ["src/api.generated.ts", "generated"],
    ["src/__generated__/schema.ts", "generated"],
    ["proto/user.pb.go", "generated"],
    ["proto/user_pb2.py", "generated"],
    ["src/__snapshots__/view.test.ts.snap", "generated"],
    ["dist/index.js", "build-output"],
    ["packages/core/dist/index.d.ts", "build-output"],
    ["build/app.js", "build-output"],
    [".next/server/page.js", "build-output"],
    ["src/index.js.map", "build-output"],
    ["vendor/github.com/pkg/errors/errors.go", "vendored"],
    ["node_modules/left-pad/index.js", "vendored"],
    ["third_party/zlib/zlib.h", "vendored"],
    [".yarn/releases/yarn-4.cjs", "vendored"],
  ])("skips %s as %s", (path, reason) => {
    expect(skip(diff(path))?.reason).toBe(reason);
  });

  it.each([
    "src/index.ts",
    "README.md",
    "package.json",
    "src/lock.ts",
    "src/distance.ts",
    "src/builder/index.ts",
    "docs/vendoring.md",
    "src/min.js",
  ])("keeps %s", (path) => {
    expect(skip(diff(path))).toBeUndefined();
  });

  it("names the glob that matched", () => {
    expect(skip(diff("a/b/yarn.lock"))).toEqual({ reason: "lockfile", glob: "**/yarn.lock" });
  });

  it("skips binaries whatever their path", () => {
    expect(skip(diff("src/logo.png", { binary: true }))).toEqual({ reason: "binary" });
  });

  it("keeps submodule bumps, so a surprising one can be flagged", () => {
    expect(skip(diff("libs/shared", { submodule: true }))).toBeUndefined();
  });

  it("adds the repo's skip globs to the defaults", () => {
    const custom = skipClassifier(["docs/**", "**/*.csv"]);
    expect(custom(diff("docs/guide.md"))).toEqual({ reason: "config", glob: "docs/**" });
    expect(custom(diff("data/rows.csv"))).toEqual({ reason: "config", glob: "**/*.csv" });
    expect(custom(diff("yarn.lock"))?.reason).toBe("lockfile");
    expect(custom(diff("src/index.ts"))).toBeUndefined();
  });

  it("skips files with a generated marker in their header", () => {
    const go = diff("api/client.go", {
      hunks: [header("// Code generated by protoc-gen-go. DO NOT EDIT.")],
    });
    expect(skip(go)).toEqual({ reason: "generated" });
  });
});

describe("hasGeneratedMarker", () => {
  it.each([
    "// Code generated by sqlc. DO NOT EDIT.",
    "/* @generated */",
    "# This file is auto-generated. Do not edit.",
    "// Autogenerated file, do not modify",
  ])("finds %s", (text) => {
    expect(hasGeneratedMarker(diff("x.ts", { hunks: [header(text)] }))).toBe(true);
  });

  it("only looks at the first lines", () => {
    const deep = diff("x.go", { hunks: [header("// Code generated. DO NOT EDIT.", 40)] });
    expect(hasGeneratedMarker(deep)).toBe(false);
  });

  it("ignores deleted lines, since the head no longer has them", () => {
    const hunk: Hunk = {
      ...header(""),
      lines: [{ kind: "del", oldLine: 1, text: "// Code generated. DO NOT EDIT." }],
    };
    expect(hasGeneratedMarker(diff("x.go", { hunks: [hunk] }))).toBe(false);
  });

  it("ignores ordinary comments", () => {
    expect(hasGeneratedMarker(diff("x.ts", { hunks: [header("// generates the token")] }))).toBe(
      false,
    );
  });
});

describe("TEST_GLOBS", () => {
  const isTest = globMatcher(TEST_GLOBS);

  it.each([
    "src/plan.test.ts",
    "plan.test.ts",
    "src/plan.spec.js",
    "src/__tests__/plan.ts",
    "test/plan.ts",
    "packages/a/tests/unit/plan.py",
    "pkg/plan_test.go",
    "tests_dir/test_plan.py",
    "app/models/user_spec.rb",
    "src/main/java/PlanTest.java",
    "pkg/testdata/input.txt",
    "src/fixtures/user.json",
  ])("treats %s as a test", (path) => {
    expect(isTest(path)).toBeDefined();
  });

  it.each(["src/plan.ts", "src/testing.ts", "src/contest/entry.ts", "src/latest.py"])(
    "doesn't treat %s as a test",
    (path) => {
      expect(isTest(path)).toBeUndefined();
    },
  );
});

describe("globMatcher", () => {
  it("returns the first glob that matches, and matches dotfiles", () => {
    const match = globMatcher(["src/**", "**/.github/**", "**/*.ts"]);
    expect(match("src/a.ts")).toBe("src/**");
    expect(match(".github/workflows/ci.yml")).toBe("**/.github/**");
    expect(match("lib/a.ts")).toBe("**/*.ts");
    expect(match("lib/a.js")).toBeUndefined();
  });
});
